#!/usr/bin/env bash
# Usage: scripts/test-bundle-ids.sh [--built]   Check identifiers and, optionally, built app names.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
cd "$repo_root"

if [[ "$(uname -s)" != Darwin || ! -d iMessageRiff.xcodeproj ]]; then
    echo "test-bundle-ids: requires macOS and the project generated by scripts/bootstrap.sh." >&2
    exit 1
fi
if [[ $# -gt 1 ]] || { [[ $# -eq 1 ]] && [[ "$1" != "--built" ]]; }; then
    echo "usage: scripts/test-bundle-ids.sh [--built]" >&2
    exit 64
fi

python3 - "$@" <<'PY'
import json
import plistlib
import subprocess
import sys
from pathlib import Path

command = [
    "xcodebuild", "-project", "iMessageRiff.xcodeproj", "-scheme", "iMessageRiff", "-configuration", "Debug",
    "-destination", "generic/platform=iOS Simulator", "-showBuildSettings", "-json",
]
cases = [
    ("prefix default", [
        "RIFF_BUNDLE_PREFIX=example.test",
        "RIFF_APP_BUNDLE_IDENTIFIER=$(RIFF_BUNDLE_PREFIX).iMessageRiff",
    ], "example.test.iMessageRiff"),
    ("registered app ID", [
        "RIFF_BUNDLE_PREFIX=example.test",
        "RIFF_APP_BUNDLE_IDENTIFIER=example.test.ExistingApp",
    ], "example.test.ExistingApp"),
]
if not Path("Config/Local.xcconfig").exists():
    cases.append(("repository default", [], "dev.imessageriff.placeholder.iMessageRiff"))

for name, overrides, app_id in cases:
    result = subprocess.run(command + overrides, capture_output=True, text=True)
    if result.returncode:
        sys.exit(f"{name}: xcodebuild failed:\n{result.stderr}")
    settings = {item["target"]: item["buildSettings"] for item in json.loads(result.stdout)}
    for target, expected in (("iMessageRiff", app_id), ("iMessageRiffMessages", app_id + ".MessagesExtension")):
        target_settings = settings.get(target, {})
        actual = target_settings.get("PRODUCT_BUNDLE_IDENTIFIER")
        if actual != expected:
            sys.exit(f"{name}: {target} bundle ID was {actual!r}, expected {expected!r}")
        if target_settings.get("RIFF_DISPLAY_NAME") != "iMessageRiff":
            sys.exit(f"{name}: {target} does not use the iMessageRiff display name")
    print(f"PASS {name}")

if sys.argv[1:] == ["--built"]:
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode:
        sys.exit(f"built app: xcodebuild failed:\n{result.stderr}")
    settings = {item["target"]: item["buildSettings"] for item in json.loads(result.stdout)}
    app_settings = settings["iMessageRiff"]
    extension_settings = settings["iMessageRiffMessages"]
    app = Path(app_settings["TARGET_BUILD_DIR"]) / app_settings["FULL_PRODUCT_NAME"]
    for name, info_path, target_settings in (
        ("app", app / "Info.plist", app_settings),
        ("embedded extension", app / "PlugIns" / extension_settings["FULL_PRODUCT_NAME"] / "Info.plist",
         extension_settings),
    ):
        if not info_path.is_file():
            sys.exit(f"built {name}: Info.plist not found; build the iOS Simulator app first")
        with info_path.open("rb") as handle:
            info = plistlib.load(handle)
        if info.get("CFBundleDisplayName") != "iMessageRiff":
            sys.exit(f"built {name}: incorrect display name")
        if info.get("CFBundleIdentifier") != target_settings["PRODUCT_BUNDLE_IDENTIFIER"]:
            sys.exit(f"built {name}: bundle identifier differs from build settings")
        if name == "embedded extension":
            principal = info.get("NSExtension", {}).get("NSExtensionPrincipalClass")
            expected = target_settings["PRODUCT_MODULE_NAME"] + ".MessagesViewController"
            if principal != expected:
                sys.exit("built extension: principal class differs from the renamed module")
        print(f"PASS built {name} name and identifier")
PY
