#!/usr/bin/env bash
# Usage: scripts/test-bundle-ids.sh   Check generated app and extension identifiers on macOS.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
cd "$repo_root"

if [[ "$(uname -s)" != Darwin || ! -d Riff.xcodeproj ]]; then
    echo "test-bundle-ids: requires macOS and the project generated by scripts/bootstrap.sh." >&2
    exit 1
fi

python3 - <<'PY'
import json
import subprocess
import sys
from pathlib import Path

command = [
    "xcodebuild", "-project", "Riff.xcodeproj", "-scheme", "Riff", "-configuration", "Debug",
    "-destination", "generic/platform=iOS Simulator", "-showBuildSettings", "-json",
]
cases = [
    ("prefix default", [
        "RIFF_BUNDLE_PREFIX=example.test",
        "RIFF_APP_BUNDLE_IDENTIFIER=$(RIFF_BUNDLE_PREFIX).Riff",
    ], "example.test.Riff"),
    ("registered app ID", [
        "RIFF_BUNDLE_PREFIX=example.test",
        "RIFF_APP_BUNDLE_IDENTIFIER=example.test.ExistingApp",
    ], "example.test.ExistingApp"),
]
if not Path("Config/Local.xcconfig").exists():
    cases.append(("repository default", [], "dev.riff.placeholder.Riff"))

for name, overrides, app_id in cases:
    result = subprocess.run(command + overrides, capture_output=True, text=True)
    if result.returncode:
        sys.exit(f"{name}: xcodebuild failed:\n{result.stderr}")
    settings = {item["target"]: item["buildSettings"] for item in json.loads(result.stdout)}
    for target, expected in (("Riff", app_id), ("RiffMessages", app_id + ".MessagesExtension")):
        actual = settings.get(target, {}).get("PRODUCT_BUNDLE_IDENTIFIER")
        if actual != expected:
            sys.exit(f"{name}: {target} bundle ID was {actual!r}, expected {expected!r}")
    print(f"PASS {name}")
PY
